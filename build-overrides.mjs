#!/usr/bin/env node
/**
 * Regenerates overrides.js from data/overrides.json (mirrors how scrape.mjs
 * turns data/games.json into games.js). Run this after hand-editing
 * data/overrides.json; scan-modes.mjs also calls this automatically.
 */
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const __dirname = dirname(fileURLToPath(import.meta.url));

async function main() {
  const json = await readFile(join(__dirname, "data", "overrides.json"), "utf8");
  const overrides = JSON.parse(json);
  await writeFile(
    join(__dirname, "overrides.js"),
    `// Auto-generated by build-overrides.mjs from data/overrides.json — do not edit by hand.\nwindow.GAMES_OVERRIDES = ${JSON.stringify(overrides)};\n`,
    "utf8"
  );
  console.log("✓ Wrote overrides.js from data/overrides.json");
}

main().catch((err) => {
  console.error("build-overrides failed:", err);
  process.exit(1);
});
